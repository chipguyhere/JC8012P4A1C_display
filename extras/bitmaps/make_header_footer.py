#!/usr/bin/env python3
"""
make_header_footer.py - the pre-rendered header and footer images for the
TerminalHeaderFooter example, as RGB565 arrays.

  python3 make_header_footer.py DejaVuSans-Bold.ttf DejaVuSans.ttf \
      ../../examples/TerminalHeaderFooter/bitmaps.h

Both are 1280 pixels wide, the panel's long side, so they span the screen in
landscape.  The sketch draws them centered, so in portrait (800 wide) 240
pixels drop off each side, and at the terminal's 480 resolution 400; keep
anything that matters inside the middle 480 (x 400..879).  Both are 40 tall,
two 20-pixel text lines and a multiple of 8 (which the 480 resolution's
1.625x scale needs), so every mode has whole lines between them.  Needs
Pillow.

(Adapted from chipguy_P486Panel_display's, which draws 720-wide images, and
that from chipguy_ESP32-CYD-Resistive_display's 320-wide ones.)
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, HH, FH = 1280, 40, 40
X0 = (W - 480) // 2      # the middle 480, which every mode shows

def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)

def header(bold, regular):
    im = Image.new('RGB', (W, HH))
    d = ImageDraw.Draw(im)
    for x in range(W):                       # navy to teal
        t = x / (W - 1)
        d.line([(x, 0), (x, HH - 1)], fill=(int(10 + 10 * t), int(30 + 110 * t), int(90 + 60 * t)))
    d.line([(0, HH - 3), (W, HH - 3)], fill=(255, 200, 0), width=3)
    d.text((W // 2, 14), 'JC8012 TERMINAL', font=ImageFont.truetype(bold, 18), fill='white', anchor='mm')
    d.text((W // 2, 30), 'frozen header  •  scrolling text below',
           font=ImageFont.truetype(regular, 11), fill=(200, 230, 255), anchor='mm')
    return im

def footer(regular):
    im = Image.new('RGB', (W, FH), (32, 32, 40))
    d = ImageDraw.Draw(im)
    d.line([(0, 0), (W, 0)], fill=(255, 200, 0), width=3)
    # X0..X0+480 is the part the 480 resolution shows.
    d.text((X0 + 12, 21), 'activity', font=ImageFont.truetype(regular, 13), fill=(180, 180, 190), anchor='lm')
    d.rectangle([X0 + 149, 13, X0 + 469, 29], outline=(120, 120, 130))   # the bar's frame
    return im

def c_array(name, im):
    px = [rgb565(*p) for p in im.getdata()]
    out = [f'// {im.width} x {im.height} RGB565, row by row.',
           f'static const uint16_t {name}[{im.width * im.height}] = {{']
    for k in range(0, len(px), 16):
        out.append('    ' + ', '.join(f'0x{v:04X}' for v in px[k:k + 16]) + ',')
    out.append('};')
    return '\n'.join(out) + '\n'

bold, regular, out = sys.argv[1:4]
with open(out, 'w') as f:
    f.write('// Generated by extras/bitmaps/make_header_footer.py - do not edit.\n'
            '// Text set in DejaVu Sans (Bitstream Vera license).\n#pragma once\n#include <stdint.h>\n\n')
    f.write(f'#define HEADER_W {W}\n#define HEADER_H {HH}\n#define FOOTER_W {W}\n#define FOOTER_H {FH}\n')
    f.write('// The footer\'s activity bar: inside the frame drawn into the image.\n'
            f'#define BAR_X {X0 + 150}\n#define BAR_Y 14\n#define BAR_W 319\n#define BAR_H 15\n\n')
    f.write(c_array('kHeader', header(bold, regular)))
    f.write('\n')
    f.write(c_array('kFooter', footer(regular)))
